/*
AST (Abstract Syntax Tree, абстрактное синтаксическое дерево)

Что это. Дерево, представляющее структуру выражения. Плоский список токенов не показывает
вложенность и приоритеты — дерево показывает.

Выражение:

tcp and (port 80 or port 443)

AST:

        AND
       /   \
   PROTO    OR
   (tcp)   /  \
        PORT   PORT
        (80)   (443)

Теперь из дерева однозначно видно: сначала «port 80 или port 443», и только потом это всё «and tcp».
Скобки уже «впечатаны» в форму дерева, их больше не существует как токенов.

Зачем. Дерево — идеальная промежуточная форма. По нему легко:

проверить смысл («port» должен быть с числом, не с IP)
сгенерировать код рекурсивно (обошёл дерево — получил байт-код)
*/

