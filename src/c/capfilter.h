/*
BPF (Berkeley Packet Filter)

Что это. Крошечная виртуальная машина внутри ядра Linux. У неё есть:

регистр A (аккумулятор) и регистр X
«память» M[0..15]
программа = массив инструкций фиксированного формата по 8 байт

Каждая инструкция — { code, jt, jf, k }:

code — что делать (загрузить байт, сравнить, вернуть результат)
k — операнд (смещение в пакете, константа для сравнения)
jt / jf — «на сколько инструкций прыгнуть, если условие истинно / ложно»

Как работает. Ты подаёшь программу ядру через setsockopt(SO_ATTACH_FILTER). Дальше на каждый
пришедший кадр ядро запускает эту программу: она смотрит на байты пакета и возвращает число —
сколько байт пропустить наверх. 0 = выбросить пакет, большое число = отдать целиком в user space.

Зачем. Фильтрация происходит в ядре, до копирования пакета в твою программу. tcpdump "tcp port 443"
не гоняет весь трафик через user space — ядро отсекает лишнее сразу. Это и скорость, и то, что твой
процесс вообще не видит ненужные пакеты.

Пример. Фильтр «только IPv4» на человеческом:

A = 2 байта на смещении 12 (поле EtherType)
если A == 0x0800 → вернуть "пропустить"
иначе            → вернуть 0
В байт-коде:

{ BPF_LD|BPF_H|BPF_ABS, 0, 0, 12      }   // A = frame[12:2]
{ BPF_JMP|BPF_JEQ|BPF_K, 0, 1, 0x0800 }   // A==0x0800? нет → прыг на +1
{ BPF_RET|BPF_K,         0, 0, 262144 }   // accept
{ BPF_RET|BPF_K,         0, 0, 0      }   // reject
*/

/*
Лексер (lexer, «токенизатор»)

Что это. Первая стадия. Превращает строку символов в поток токенов (осмысленных «слов»).

На входе:

"tcp port 443"

На выходе:

[ PROTO(tcp) ] [ PORT ] [ NUM(443) ] [ END ]

Что он делает конкретно:

пропускает пробелы
собирает подряд идущие буквы/цифры/точки в «слово»
классифицирует слово: это ключевое слово (tcp, port, and)? число? IP-адрес?
распознаёт символы-операторы: (, ), !, &&, ||

Зачем отдельная стадия. Чтобы парсер не возился с отдельными символами. Парсеру гораздо проще
работать с «дай следующий токен», чем «прочитай букву, потом ещё букву, реши, кончилось ли слово».
Разделение забот: лексер знает про символы, парсер — про грамматику.

*/

