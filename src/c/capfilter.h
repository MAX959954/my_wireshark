/*
Рекурсивный спуск (recursive descent parsing)

Что это. Способ построить AST из токенов. «Спуск» — потому что идём от самого общего правила
грамматики к самому частному. «Рекурсивный» — потому что каждое правило грамматики становится
функцией, и функции вызывают друг друга (в том числе себя).

Идея. Грамматика записана правилами:

or   := and ( 'or' and )*
and  := not ( 'and'? not )*
not  := '!' not | primary
primary := '(' expr ')' | primitive

Каждое правило → одноимённая функция:

parse_or()   вызывает parse_and()  в цикле, пока видит 'or'
parse_and()  вызывает parse_not()  в цикле, пока видит 'and' или начало примитива
parse_not()  вызывает сам себя после '!', иначе parse_primary()
parse_primary() при '(' вызывает parse_expr() и ждёт ')'

Почему приоритет операторов получается сам собой. or стоит «выше» в цепочке вызовов, and — «ниже»,
not — ещё ниже. Значит not связывается первым (самый глубокий уровень рекурсии), and вторым, or
последним. Ровно то, что мы хотим: a or b and c = a or (b and c).

Пример разбора tcp or udp:

parse_or:
  left = parse_and:
           left = parse_not → parse_primary → parse_primitive → PROTO(tcp)
           следующий токен 'or' — это не 'and' и не начало примитива → выходим
           вернуть PROTO(tcp)
  видим 'or' → съедаем его
  right = parse_and → ... → PROTO(udp)
  строим узел OR(tcp, udp)
  вернуть OR(tcp, udp)

Зачем именно рекурсивный спуск. Он пишется руками, без генераторов вроде yacc/bison, читается
один-в-один как грамматика, и его легко отлаживать. Для маленького языка (десяток правил) —
идеальный выбор.

*/





/*
Компилирует 'expr' в *out.  При успехе возвращает 0 и заполняет out->filter
(в куче, освобождать через capfilter_free) и out->len.  NULL или пустое
выражение — не ошибка: даёт out->len == 0 / out->filter == NULL, что означает
"пропускать каждый пакет" — в этом случае вызывающий код должен пропустить
вызов SO_ATTACH_FILTER.

При синтаксической ошибке или слишком сложном выражении возвращает -1 и
записывает человекочитаемую причину в 'err' (буфер размера 'err_len' байт;
может быть NULL).
*/
int capfilter_compile(const char* expr, struct sock_fprog* out, char* err, int err_len);


/* Освобождает out->filter и обнуляет структуру.  Безопасно для нулевой /
   NULL программы. */
void capfilter_free(struct sock_fprog* fprog);


/* Для отладки: печатает программу по одной инструкции на строку.  Сверяй с
   выводом `tcpdump -dd "<expr>"` при разработке кодогенератора. */
void capfilter_print(const struct sock_fprog* fprog);

